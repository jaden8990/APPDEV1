const grade = 87;

if (grade >= 90) {
  console.log("Grade: A");
} else if (grade >= 80) {
  console.log("Grade: B");
} else if (grade >= 70) {
  console.log("Grade: C");
} else {
  console.log("Grade: F");
}

// for loop: print 1 to 5
for (let number = 1; number <= 5; number++) {
  console.log(number);
}

// while loop: print "Hello" 3 times
let count = 0;

while (count < 3) {
  console.log("Hello");
  count++;
}